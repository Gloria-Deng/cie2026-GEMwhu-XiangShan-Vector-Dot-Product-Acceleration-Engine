#!/usr/bin/env bash














set -u
export PATH="$PATH:/e/msys64/usr/bin"
HERE="$(cd "$(dirname "$0")/../.." && pwd)"
PY=/c/Users/lenovo/AppData/Local/Programs/Python/Python311/python
WORK="${COSIM_WORK:-/d/nemu_cosim}"
COSIM_DLL="${COSIM_DLL:-/d/nemu-cosim/build/riscv64-nemu-interpreter-so.exe}"
CTRL_DLL="${CTRL_DLL:-/d/nemu-vanilla-cosimarm/build/riscv64-nemu-interpreter-so.exe}"
OUT="$HERE/results/nemu_cosim_baseline.txt"

cd "$WORK" || { echo "SETUP-FAIL: $WORK missing (see nemu/cosim/build_cosim.sh)"; exit 2; }
for f in "$COSIM_DLL" "$CTRL_DLL" cosim_baseline.exe; do
  [ -e "$f" ] || { echo "SETUP-FAIL: $f missing"; exit 2; }
done

$PY "$HERE/nemu/cosim/rtl_vectors_to_cosim.py" cases_rtl.txt > /dev/null \
  || { echo "SETUP-FAIL: vector bridge failed"; exit 2; }

sha_of () { $PY -c "import hashlib,sys;b=open(sys.argv[1],'rb').read();print(hashlib.sha256(b).hexdigest(), len(b))" "$1"; }
read SHA SIZE <<<"$(sha_of "$COSIM_DLL")";  COSIM_SHA="$SHA"; COSIM_SIZE="$SIZE"
read SHA SIZE <<<"$(sha_of "$CTRL_DLL")";   CTRL_SHA="$SHA";  CTRL_SIZE="$SIZE"




read SHA SIZE <<<"$(sha_of cosim_baseline.exe)"; EXE_SHA="$SHA"; EXE_SIZE="$SIZE"
PKG_BASE_C="$HERE/nemu/cosim/cosim_baseline.c"
read SHA SIZE <<<"$(sha_of "$PKG_BASE_C")"; SRC_SHA="$SHA"









need () { [ -n "$2" ] || { echo "SETUP-FAIL: $1 came out empty"; exit 2; }; }
need "harness exe sha" "$EXE_SHA"
need "harness source sha" "$SRC_SHA"
read SHA SIZE <<<"$(sha_of cosim_baseline.c)"; WORK_SRC="$SHA"
need "work-copy sha" "$WORK_SRC"
[ "$WORK_SRC" = "$SRC_SHA" ] || { echo "SETUP-FAIL: $WORK/cosim_baseline.c != $PKG_BASE_C (the exe this archive describes was built from a different source than the package ships)"; exit 2; }
BRIDGE="$HERE/nemu/cosim/rtl_vectors_to_cosim.py"
read SHA SIZE <<<"$(sha_of "$BRIDGE")";        BRIDGE_SHA="$SHA"; need "bridge sha" "$BRIDGE_SHA"
read SHA SIZE <<<"$(sha_of cases_rtl.txt)";    CASES_SHA="$SHA"; CASES_BYTES="$SIZE"; need "cases sha" "$CASES_SHA"
CASES_LINES=$(grep -c -v '^#' cases_rtl.txt);  need "cases line count" "$CASES_LINES"
COMPOSITION=$($PY "$BRIDGE" --composition);    need "case composition" "$COMPOSITION"


{
  echo "# generated by nemu/cosim/capture_baseline_cosim.sh -- do not edit"
  echo "cases file: cases_rtl.txt source: tests/cases_{pos,neg,bound,rand}.txt"
  echo "[dll] cosim-arm path=$COSIM_DLL sha256=$COSIM_SHA size=$COSIM_SIZE"
  echo "[dll] control-arm path=$CTRL_DLL sha256=$CTRL_SHA size=$CTRL_SIZE"
  echo "[harness] exe path=$WORK/cosim_baseline.exe sha256=$EXE_SHA size=$EXE_SIZE source_sha256=$SRC_SHA work_copy_sha256=$WORK_SRC"
  echo "[bridge] script_sha256=$BRIDGE_SHA cases_path=$WORK/cases_rtl.txt cases_sha256=$CASES_SHA cases_bytes=$CASES_BYTES cases_lines=$CASES_LINES inputs=$COMPOSITION"
  echo ""



  for v in doc3 e16 vwred vwred-g vwmacc3 vwmacc4 vwmacc5 vwmacc6; do
    ./cosim_baseline.exe "$COSIM_DLL" cases_rtl.txt $v > run_$v.log 2>&1
    echo "run patched $v rc=$?"
  done
  ./cosim_baseline.exe "$CTRL_DLL" cases_rtl.txt vwred > run_vwred_control.log 2>&1
  echo "run control vwred rc=$?"
  ./cosim_baseline.exe "$COSIM_DLL" cases_rtl.txt vwred --inject-bug > run_vwred_inject.log 2>&1
  echo "run inject vwred rc=$?"
  echo ""
  echo "=== the sequence as written into guest memory, each word read back ==="
  grep -a "^  \[\|^variant=" run_doc3.log run_e16.log run_vwred.log run_vwred-g.log \n    run_vwmacc3.log run_vwmacc4.log run_vwmacc5.log run_vwmacc6.log
  echo "=== first difference per failing variant ==="
  grep -a "^MISMATCH case 1\|^first difference" run_doc3.log run_e16.log run_vwmacc3.log \n    run_vwmacc4.log run_vwmacc5.log
} > "$OUT" 2>&1



{
  echo ""
  echo "[baseline-patched] $(grep -a '^cases=' run_vwred.log | tail -1)"
  echo "[baseline-control] $(grep -a '^cases=' run_vwred_control.log | tail -1)"
  echo "[positive-control] $(grep -a 'POSITIVE CONTROL' run_vwred_inject.log | tail -1)"
  echo "[variant-doc3] $(grep -a '^cases=' run_doc3.log | tail -1)"
  echo "[variant-e16] $(grep -a '^cases=' run_e16.log | tail -1)"
} >> "$OUT"








VWM_BEST=""
VWM_LINES=""
for v in vwred-g vwmacc3 vwmacc4 vwmacc5 vwmacc6; do
  L=$(grep -a '^cases=' run_$v.log | tail -1)
  if [ -z "$L" ]; then echo "SETUP-FAIL: run_$v.log has no cases= line"; exit 3; fi
  M=$(echo "$L" | sed -n 's/.*mismatches=\([0-9]*\).*/\1/p')
  N=$(echo "$L" | sed -n 's/.*n_inst=\([0-9]*\).*/\1/p')
  C=$(echo "$L" | sed -n 's/^cases=\([0-9]*\).*/\1/p')
  need "vwmacc arm $v mismatches" "$M"; need "vwmacc arm $v n_inst" "$N"; need "vwmacc arm $v cases" "$C"
  VWM_LINES="$VWM_LINES[variant-$v] $L
"
  if [ "$v" = "vwred-g" ]; then continue; fi
  if [ "$M" = "0" ]; then
    if [ -z "$VWM_BEST" ] || [ "$N" -lt "$(echo "$VWM_BEST" | sed -n 's/.*n_inst=\([0-9]*\).*/\1/p')" ]; then
      VWM_BEST="$L"
    fi
  fi
done
{
  echo ""
  printf '%s' "$VWM_LINES"
  BASE_N=$(grep -a '^\[baseline-patched\]' "$OUT" | tail -1 | sed -n 's/.*n_inst=\([0-9]*\).*/\1/p')
  need "the delivered baseline's measured instruction count" "$BASE_N"
  if [ -z "$VWM_BEST" ]; then
    echo "[variant-vwmacc] no arm in the ladder reproduced the golden value -- nothing to compare"
    echo "VWMACC_NOT_SHORTER n_inst=UNREACHABLE min_current=$BASE_N"
  else
    BN=$(echo "$VWM_BEST" | sed -n 's/.*n_inst=\([0-9]*\).*/\1/p')
    echo "[variant-vwmacc] $VWM_BEST"
    echo "VWMACC_MEASURED shortest_correct_vwmacc_form=$BN vwmacc_family_all_n_inst=3,4,5,6"
    if [ "$BN" -lt "$BASE_N" ]; then
      echo "VWMACC_SHORTER n_inst=$BN min_current=$BASE_N   <-- THE DELIVERED BASELINE IS NOT OPTIMAL"
    else
      echo "VWMACC_NOT_SHORTER n_inst=$BN min_current=$BASE_N"
    fi
  fi
} >> "$OUT"

echo "CAPTURE_RC=$?"
cat "$OUT"
