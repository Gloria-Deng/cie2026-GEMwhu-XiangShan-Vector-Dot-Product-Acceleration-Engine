#!/usr/bin/env bash









set -u
export PATH="$PATH:/e/msys64/usr/bin"
HERE="$(cd "$(dirname "$0")/../.." && pwd)"
PY=/c/Users/lenovo/AppData/Local/Programs/Python/Python311/python
WORK="${COSIM_WORK:-/d/nemu_cosim}"
COSIM_DLL="${COSIM_DLL:-/d/nemu-cosim/build/riscv64-nemu-interpreter-so.exe}"
CTRL_DLL="${CTRL_DLL:-/d/nemu-vanilla-cosimarm/build/riscv64-nemu-interpreter-so.exe}"
OUT="$HERE/results/nemu_cosim_seq.txt"
NCASE="${NCASE:-936}"

cd "$WORK" || { echo "SETUP-FAIL: $WORK missing"; exit 2; }
for f in "$COSIM_DLL" "$CTRL_DLL" cosim_seq.exe cases_rtl.txt; do
  [ -e "$f" ] || { echo "SETUP-FAIL: $f missing (build it with nemu/cosim/build_cosim.sh)"; exit 2; }
done
sha_of () { $PY -c "import hashlib,sys;b=open(sys.argv[1],'rb').read();print(hashlib.sha256(b).hexdigest(), len(b))" "$1"; }
need () { [ -n "$2" ] || { echo "SETUP-FAIL: $1 came out empty"; exit 2; }; }


$PY - "$NCASE" <<'PYEOF' || { echo "SETUP-FAIL: golden expectation generator failed"; exit 2; }
import io, os, sys
sys.path.insert(0, r"D:\Desktop\RSIC-V香山\submission\sim")
import golden_vdot as G
n = int(sys.argv[1])
rows = [l.split() for l in io.open("cases_rtl.txt", encoding="utf-8")
        if l.strip() and not l.startswith("#")]
assert len(rows) >= n, "cases_rtl.txt has %d rows, asked for %d" % (len(rows), n)
out = ["# vs1(16B hex) vs2(16B hex) expect v1 after step2 | v12 after step3 | v2 after step4"]
for a, b, _want in rows[:n]:
    ab, bb = bytes.fromhex(a), bytes.fromhex(b)
    step2 = G.vdot_vd_bits(ab, bb, nlanes=8, out_w=32, vlen=128)
    step3 = step2                                  # vmv.v.v v12,v1 copies it verbatim
    v1 = step2.to_bytes(16, "little")              # what v1 really holds after step2
    step4 = G.vdot_vd_bits(v1, bb, nlanes=8, out_w=32, vlen=128)
    assert v1[:8] != ab, "a degenerate second-vdot case: v1 must not equal vs1's seed"
    out.append("%s %s %08x %08x %08x" % (a, b, step2, step3, step4))
io.open("seq_cases.txt", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("seq_cases.txt rows=%d" % n)
PYEOF

read SHA SIZE <<<"$(sha_of "$COSIM_DLL")";  COSIM_SHA="$SHA";  COSIM_SIZE="$SIZE"
read SHA SIZE <<<"$(sha_of "$CTRL_DLL")";   CTRL_SHA="$SHA";   CTRL_SIZE="$SIZE"
read SHA SIZE <<<"$(sha_of cosim_seq.exe)"; EXE_SHA="$SHA";    EXE_SIZE="$SIZE"
read SHA SIZE <<<"$(sha_of cosim_seq.c)";   WORK_SRC="$SHA"
PKG_C="$HERE/nemu/cosim/cosim_seq.c"
read SHA SIZE <<<"$(sha_of "$PKG_C")";      PKG_SRC="$SHA"
[ "$WORK_SRC" = "$PKG_SRC" ] || { echo "SETUP-FAIL: $WORK/cosim_seq.c != $PKG_C (the exe this archive describes was built from a different source than the package ships)"; exit 2; }
read SHA SIZE <<<"$(sha_of seq_cases.txt)"; SEQ_SHA="$SHA";    SEQ_BYTES="$SIZE"
SEQ_ROWS=$(grep -c -v '^#' seq_cases.txt)
for v in EXE_SHA WORK_SRC PKG_SRC SEQ_SHA SEQ_ROWS; do need "$v" "$(eval echo \$$v)"; done

AS=/e/msys64/ucrt64/bin/riscv64-unknown-elf-as.exe
OD=/e/msys64/ucrt64/bin/riscv64-unknown-elf-objdump.exe
[ -x "$AS" ] || { echo "SETUP-FAIL: assembler $AS missing -- the standard words in cosim_seq.c would then have no live provenance"; exit 2; }



printf '.text\nvsetivli zero,8,e16,m1,ta,ma\nvmv.v.i v13,0\nvsetivli zero,8,e8,m1,ta,ma\nvmv.v.i v14,0\nvmv.v.v v12,v1\n' > "$WORK/seq_words.S"
ASMLOG=$($AS --version | head -1)
need "assembler banner" "$ASMLOG"
DISASM=$($OD -d "$WORK/seq_words.o" 2>/dev/null || { $AS -march=rv64gcv -o "$WORK/seq_words.o" "$WORK/seq_words.S" && $OD -d "$WORK/seq_words.o"; })
need "the disassembly of the sequence words" "$DISASM"
grep -q "vmv.v.v.*v12,v1" <<<"$DISASM" || { echo "SETUP-FAIL: the re-assembled words do not match the ones cosim_seq.c places"; exit 2; }

{
  echo "# generated by nemu/cosim/capture_cosim_seq.sh -- do not edit"
  echo "# requirement 3.1.2 at SEQUENCE level: 5 guest instructions in one difftest session"
  echo "[dll] cosim-arm path=$COSIM_DLL sha256=$COSIM_SHA size=$COSIM_SIZE"
  echo "[dll] control-arm path=$CTRL_DLL sha256=$CTRL_SHA size=$CTRL_SIZE"
  echo "[harness] exe path=$WORK/cosim_seq.exe sha256=$EXE_SHA size=$EXE_SIZE source_sha256=$PKG_SRC work_copy_sha256=$WORK_SRC"
  echo "[cases] seq_cases.txt path=$WORK/seq_cases.txt sha256=$SEQ_SHA bytes=$SEQ_BYTES rows=$SEQ_ROWS derived_from=cases_rtl.txt expectations=sim/golden_vdot.py"
  echo "[assembler] $AS"
  echo "[assembler-version] $ASMLOG"
  echo "[assembler-cmd] $AS -march=rv64gcv -o seq_words.o seq_words.S && $OD -d seq_words.o"
  echo "[assembler-src] $WORK/seq_words.S: vsetivli e16 / vmv.v.i v13,0 / vsetivli e8 / vmv.v.i v14,0 / vmv.v.v v12,v1"
  echo "=== objdump -d seq_words.o ==="
  echo "$DISASM" | grep -a "vsetivli\|vmv"
  echo ""
  ./cosim_seq.exe "$COSIM_DLL" seq_cases.txt > seq_patched.log 2>&1
  echo "patched-arm rc=$?"
  ./cosim_seq.exe "$CTRL_DLL" seq_cases.txt > seq_control.log 2>&1
  echo "control-arm rc=$?"
  ./cosim_seq.exe "$COSIM_DLL" seq_cases.txt --inject-bug > seq_inject.log 2>&1
  echo "positive-control rc=$?"
  echo ""
  echo "=== the sequence as placed in guest memory (each word read back) + per-step state ==="
  head -40 seq_patched.log
  echo "=== unpatched control arm (must NOT reproduce it) ==="
  grep -a "^steps=\|^library\|STEP2-BAD\|STEP1-BAD\|pc=" seq_control.log | head -6
  echo "=== positive control on the patched arm ==="
  grep -a "^steps=\|STEP2-BAD\|POSITIVE CONTROL\|COSIM_SEQ CONTROL" seq_inject.log | head -6
} > "$OUT" 2>&1


PATCH_LINE=$(grep -a '^steps=' seq_patched.log | tail -1)
CTRL_LINE=$(grep -a '^steps=' seq_control.log | tail -1)
need "patched-arm steps line" "$PATCH_LINE"
STEPS=$(echo "$PATCH_LINE" | sed -n 's/.*steps=\([0-9]*\).*/\1/p')
BAD=$(echo "$PATCH_LINE" | sed -n 's/.*mismatches=\([0-9]*\).*/\1/p')
PCBAD=$(echo "$PATCH_LINE" | sed -n 's/.*pc_steps_bad=\([0-9]*\).*/\1/p')
CTRL_BAD=$(echo "$CTRL_LINE" | sed -n 's/.*mismatches=\([0-9]*\).*/\1/p')
CTRL_OK=-1; [ -n "$CTRL_BAD" ] && CTRL_OK="$CTRL_BAD"
POS=not-detected
if [ "$CTRL_OK" != "-1" ] && [ "$CTRL_OK" != "0" ]; then POS=detected; fi
INJ=$(grep -a 'POSITIVE CONTROL' seq_inject.log | tail -1)
{
  echo ""
  echo "[seq-patched] $PATCH_LINE"
  echo "[seq-control] $CTRL_LINE"
  echo "[seq-positive-control] $INJ"
  echo "COSIM_SEQ steps=$STEPS mismatches=$BAD pos_control=$POS pc_steps_bad=$PCBAD"
  echo "$(echo "$PATCH_LINE" | sed -n 's/.*pc_steps_ok=\([0-9]*\) pc_steps_bad=[0-9]*.*/pc=advanced by 4 every step: \1/p') of $((STEPS * SEQ_ROWS)) steps across $SEQ_ROWS cases"
} >> "$OUT"

echo "SEQ_RC=$?"
grep -a "^COSIM_SEQ" "$OUT"
cat "$OUT"
