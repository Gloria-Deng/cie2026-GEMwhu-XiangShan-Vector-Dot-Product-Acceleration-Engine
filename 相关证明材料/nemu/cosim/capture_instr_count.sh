#!/usr/bin/env bash
















set -u
export PATH="$PATH:/e/msys64/usr/bin"
HERE="$(cd "$(dirname "$0")/../.." && pwd)"
PY=/c/Users/lenovo/AppData/Local/Programs/Python/Python311/python
WORK="${COSIM_WORK:-/d/nemu_cosim}"
COSIM_TREE="${COSIM_TREE:-/d/nemu-cosim}"
COSIM_DLL="${COSIM_DLL:-/d/nemu-cosim/build/riscv64-nemu-interpreter-so.exe}"
CTRL_DLL="${CTRL_DLL:-/d/nemu-vanilla-cosimarm/build/riscv64-nemu-interpreter-so.exe}"
OUT="$HERE/results/nemu_instr_count.txt"

cd "$WORK" || { echo "SETUP-FAIL: $WORK missing"; exit 2; }
for f in "$COSIM_DLL" "$CTRL_DLL" cosim_baseline.exe cases_rtl.txt; do
  [ -e "$f" ] || { echo "SETUP-FAIL: $f missing (see nemu/cosim/build_cosim.sh)"; exit 2; }
done
[ -d "$COSIM_TREE/src/cpu" ] || { echo "SETUP-FAIL: source tree $COSIM_TREE missing"; exit 2; }

sha_of () { $PY -c "import hashlib,sys;b=open(sys.argv[1],'rb').read();print(hashlib.sha256(b).hexdigest(), len(b))" "$1"; }
need () { [ -n "$2" ] || { echo "SETUP-FAIL: $1 came out empty"; exit 2; }; }
read SHA SIZE <<<"$(sha_of "$COSIM_DLL")";  COSIM_SHA="$SHA";  COSIM_SIZE="$SIZE"
read SHA SIZE <<<"$(sha_of "$CTRL_DLL")";   CTRL_SHA="$SHA";   CTRL_SIZE="$SIZE"
read SHA SIZE <<<"$(sha_of cosim_baseline.exe)"; EXE_SHA="$SHA"; EXE_SIZE="$SIZE"
read SHA SIZE <<<"$(sha_of cosim_baseline.c)";   WORK_SRC="$SHA"
PKG_C="$HERE/nemu/cosim/cosim_baseline.c"
read SHA SIZE <<<"$(sha_of "$PKG_C")";      PKG_SRC="$SHA"
[ "$WORK_SRC" = "$PKG_SRC" ] || { echo "SETUP-FAIL: $WORK/cosim_baseline.c != $PKG_C (the exe this archive describes was built from a different source than the package ships)"; exit 2; }
read SHA SIZE <<<"$(sha_of cases_rtl.txt)"; CASES_SHA="$SHA"; CASES_BYTES="$SIZE"
CASES_LINES=$(grep -c -v '^#' cases_rtl.txt)
for v in COSIM_SHA CTRL_SHA EXE_SHA PKG_SRC CASES_SHA CASES_LINES; do
  need "$v" "$(eval echo \$$v)"; done




CE="$COSIM_TREE/src/cpu/cpu-exec.c"
PR="$COSIM_TREE/src/isa/riscv64/system/priv.c"
CD="$COSIM_TREE/scripts/build.mk"
DEF_LINE=$(grep -n "^uint64_t g_nr_guest_instr = 0;" "$CE" | head -1 | cut -d: -f1)
need "the definition line of g_nr_guest_instr" "$DEF_LINE"
INC_LINES=$(grep -n "IFDEF(CONFIG_INSTR_CNT_BY_INSTR, g_nr_guest_instr += 1);" "$CE" \
            | cut -d: -f1 | paste -sd, -)
need "the increment lines of g_nr_guest_instr" "$INC_LINES"
CNT_CFG=$(grep -c "^#define CONFIG_INSTR_CNT_BY_INSTR" "$COSIM_TREE/include/generated/autoconf.h")
MCY_LINE=$(grep -n "static inline word_t get_mcycle()" "$PR" | head -1 | cut -d: -f1)
MIR_LINE=$(grep -n "static inline word_t get_minstret()" "$PR" | head -1 | cut -d: -f1)
AIC_LINE=$(grep -n "^uint64_t get_abs_instr_count_csr()" "$CE" | head -1 | cut -d: -f1)
CPI_LINE=$(grep -n "NEMU emulates a hart with CPI = 1" "$PR" | head -1 | cut -d: -f1)
RET_LINE=$(grep -n "return g_nr_guest_instr;" "$CE" | head -1 | cut -d: -f1)
MK_LINE=$(grep -n "rdynamic" "$CD" | head -1 | cut -d: -f1)
for v in MCY_LINE MIR_LINE AIC_LINE CPI_LINE RET_LINE MK_LINE; do need "grep for $v" "$(eval echo \$$v)"; done
SYMB=$(nm -g --defined-only "$COSIM_DLL" | grep -a " B g_nr_guest_instr$" | head -1)
need "the exported data symbol in the .so" "$SYMB"

{
  echo "# generated by nemu/cosim/capture_instr_count.sh -- do not edit"
  echo "# requirement 3.3, measured half: retired instructions per sequence, read out of"
  echo "# the reference library's own g_nr_guest_instr by dlsym (no declared latency here)"
  echo "[dll] cosim-arm path=$COSIM_DLL sha256=$COSIM_SHA size=$COSIM_SIZE"
  echo "[dll] control-arm path=$CTRL_DLL sha256=$CTRL_SHA size=$CTRL_SIZE"
  echo "[source-tree] cosim-arm built from $COSIM_TREE"
  echo "[harness] exe path=$WORK/cosim_baseline.exe sha256=$EXE_SHA size=$EXE_SIZE source_sha256=$PKG_SRC work_copy_sha256=$WORK_SRC"
  echo "[cases] cases_rtl.txt sha256=$CASES_SHA bytes=$CASES_BYTES lines=$CASES_LINES"
  echo ""
  echo "COUNTER_SOURCE g_nr_guest_instr cpu-exec.c:$DEF_LINE"
  echo "COUNTER increments cpu-exec.c:$INC_LINES (CONFIG_INSTR_CNT_BY_INSTR defined $CNT_CFG x in $COSIM_TREE/include/generated/autoconf.h)"
  echo "COUNTER_SYMBOL $SYMB"
  echo "COUNTER_EXPORTS -rdynamic at $COSIM_TREE/scripts/build.mk:$MK_LINE"
  echo "CSR_PATH get_mcycle() priv.c:$MCY_LINE and get_minstret() priv.c:$MIR_LINE both return X->val + get_abs_instr_count_csr()"
  echo "CSR_PATH get_abs_instr_count_csr() cpu-exec.c:$AIC_LINE returns g_nr_guest_instr (cpu-exec.c:$RET_LINE)"
  echo "CPI_MODEL priv.c:$CPI_LINE declares CPI=1 so cycle==instret"
  echo "NO_INDEPENDENT_CYCLE_WITNESS reading csrr cycle AND csrr instret would be reading the same expression twice, so this package does not do it; the measured cycle counts live in results/xs_soc/wrapper.json (RTL posedge counter, tb/tb_vdotu_soc.sv)"
  echo ""
  echo "=== build + run commands, verbatim ==="
  echo "cd $WORK"
  echo "bash cc.sh cosim_baseline.c cosim_baseline.exe        # CC_RC=0, flags recorded in cosim_cc.log"
  echo "./cosim_baseline.exe $COSIM_DLL cases_rtl.txt --multi vdot vwred     # patched arm"
  echo "./cosim_baseline.exe $CTRL_DLL  cases_rtl.txt --multi vdot vwred     # unpatched control"
  echo "./cosim_baseline.exe $COSIM_DLL cases_rtl.txt --multi vdot_low vwred # register-overlap probe"
  echo ""
  ./cosim_baseline.exe "$COSIM_DLL" cases_rtl.txt --multi vdot vwred > ic_patched.log 2>&1
  echo "patched-multi rc=$?"
  ./cosim_baseline.exe "$CTRL_DLL" cases_rtl.txt --multi vdot vwred > ic_control.log 2>&1
  echo "control-multi rc=$?"
  ./cosim_baseline.exe "$COSIM_DLL" cases_rtl.txt --multi vdot_low vwred > ic_poison.log 2>&1
  echo "poison-multi rc=$?"
  echo ""
  echo "=== patched (cosim) library: vdot.vv vs the 4-instruction baseline ==="
  grep -a "^ICOUNT\|^COUNT_CALIBRATION\|^RAW_INSTR\|^STEP_INSTR\|^INSTR \|^NEMU_INSTR_COUNT\|^cases=" ic_patched.log
  echo ""
  echo "=== UNPATCHED control library: same arms, same counter ==="
  grep -a "^ICOUNT\|^COUNT_CALIBRATION\|^RAW_INSTR\|^STEP_INSTR\|^INSTR \|^NEMU_INSTR_COUNT\|^cases=" ic_control.log
  echo ""
  echo "=== register-overlap probe (see VD_POISON below) ==="
  grep -a "^ICOUNT\|^INSTR \|^cases=\|MISMATCH case 1" ic_poison.log | head -5
} > "$OUT" 2>&1








P=$(grep -a '^INSTR ' ic_patched.log | tail -1)
POK=$(grep -a '^NEMU_INSTR_COUNT' ic_patched.log | tail -1)
need "patched INSTR line" "$P"
PV=$(echo "$P" | sed -n 's/.*vdot=\([0-9]*\).*/\1/p')
BV=$(echo "$P" | sed -n 's/.* baseline=\([0-9]*\).*/\1/p')
RT=$(echo "$P" | sed -n 's/.*ratio=\([0-9.]*\).*/\1/p')
PMISM=$(echo "$P" | sed -n 's/.*vdot_mismatches=\([0-9]*\).*/\1/p')
BMISM=$(echo "$P" | sed -n 's/.*baseline_mismatches=\([0-9]*\).*/\1/p')
CPV=$(grep -a '^ICOUNT arm=vdot ' ic_control.log | tail -1 | sed -n 's/.*per_seq=\([0-9]*\).*/\1/p')
CBV=$(grep -a '^ICOUNT arm=vwred' ic_control.log | tail -1 | sed -n 's/.*per_seq=\([0-9]*\).*/\1/p')
CCAL=$(grep -a '^INSTR UNAVAILABLE\|^COUNT_CALIBRATION' ic_control.log | tail -1)
PBAD=$(grep -a '^INSTR ' ic_poison.log | tail -1 | sed -n 's/.*baseline_mismatches=\([0-9]*\).*/\1/p')
for v in PV BV RT PMISM BMISM CPV CBV PBAD; do need "control/poison field $v" "$(eval echo \$$v)"; done
OK_FIELD=$(echo "$POK" | sed -n 's/^NEMU_INSTR_COUNT ok=\([01]\).*/\1/p')
DV0=$(echo "$POK" | sed -n 's/.*vdot=[0-9]* declared=\([0-9]*\).*/\1/p')
DV1=$(echo "$POK" | sed -n 's/.*baseline=[0-9]* declared=\([0-9]*\).*/\1/p')
FACTOR=$(echo "$POK" | sed -n 's/.*factor=\([0-9.]*\).*/\1/p')
need "the harness's own ok= field" "$OK_FIELD"
need "the harness's declared step counts" "$DV0$DV1"
if [ "$PV" = "0" ] || [ "$BV" = "0" ]; then echo "SETUP-FAIL: a measured count came out 0"; exit 3; fi
if [ "$BV" -le "$PV" ]; then
  echo "SETUP-FAIL: the baseline retired $BV instructions and vdot $PV -- the ratio is not"
  echo "  what the claim needs and the counter is suspect"; exit 3; fi
if [ "$CBV" != "$BV" ]; then
  echo "SETUP-FAIL: the baseline sequence retired $BV instructions on the patched library"
  echo "  but $CBV on the control one -- the count would then be a property of the patch,"
  echo "  not of the sequence, and no ratio built from either number is meaningful"; exit 3; fi
OK=0



if [ "$OK_FIELD" = "1" ] && [ "$DV0" = "$PV" ] && [ "$DV1" = "$BV" ] \
   && [ "$FACTOR" = "1.00" ] && [ "$PMISM" = "0" ] && [ "$BMISM" = "0" ]; then OK=1; fi
{
  echo ""
  echo "DECODED ok_field=$OK_FIELD declared=$DV0,$DV1 factor=$FACTOR patched_mismatches=$PMISM,$BMISM control_vdot=$CPV control_baseline=$CBV poison_baseline_mismatches=$PBAD"
  echo "INSTR vdot=$PV baseline=$BV ratio=$RT arm=patched"
  echo "INSTR vdot=$CPV baseline=$CBV ratio=undefined arm=unpatched_control"
  echo "CONTROL_LINE \"$CCAL\""
  echo "CONTROL_BASELINE_MATCH measured_baseline_instructions_patched=$BV unpatched=$CBV equal=1"
  echo "VD_POISON previous-phase-destination=v1 re-pushed-with=0x80 then ONE executed step later reads back as the pre-write value: detected_baseline_mismatches=$PBAD (same sequence pair on disjoint registers: mismatches=$BMISM). Measured in this run. It reproduces with a standard vmv.v.v in the earlier phase too, so it is NOT attributed to the vdot patch -- it is a property of this difftest build's regcpy. Mechanism not root-caused. Consequence for this package: the ratio arms use disjoint register sets, and results/nemu_cosim_seq.txt runs its seven instructions inside ONE push, which is the case that does not depend on this behaviour (measured: $PV/$BV counts and per-step witness lines in that file)."
  echo "NEMU_INSTR_COUNT ok=$OK"
} >> "$OUT"
echo "IC_RC=$?"
grep -a "^NEMU_INSTR_COUNT\|^INSTR \|^COUNTER_SOURCE\|^CPI_MODEL\|^CONTROL_BASELINE" "$OUT"
