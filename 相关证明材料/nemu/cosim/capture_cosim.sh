#!/usr/bin/env bash







set -u
export PATH="$PATH:/e/msys64/usr/bin:/e/msys64/ucrt64/bin"
HERE="$(cd "$(dirname "$0")/../.." && pwd)"
PY=/c/Users/lenovo/AppData/Local/Programs/Python/Python311/python
WORK="${COSIM_WORK:-/d/nemu_cosim}"
COSIM_DLL="${COSIM_DLL:-/d/nemu-cosim/build/riscv64-nemu-interpreter-so.exe}"
CTRL_DLL="${CTRL_DLL:-/d/nemu-vanilla-cosimarm/build/riscv64-nemu-interpreter-so.exe}"
OUT="$HERE/results/nemu_cosim.txt"

cd "$WORK" || { echo "SETUP-FAIL: $WORK missing (see nemu/cosim/build_cosim.sh)"; exit 2; }
for f in "$COSIM_DLL" "$CTRL_DLL" cosim_vdot.exe; do
  [ -e "$f" ] || { echo "SETUP-FAIL: $f missing"; exit 2; }
done

$PY "$HERE/nemu/cosim/rtl_vectors_to_cosim.py" cases_rtl.txt > /dev/null \
  || { echo "SETUP-FAIL: vector bridge failed"; exit 2; }

sha_of () { $PY -c "import hashlib,sys;b=open(sys.argv[1],'rb').read();print(hashlib.sha256(b).hexdigest(), len(b))" "$1"; }
read SHA SIZE <<<"$(sha_of "$COSIM_DLL")"
COSIM_SHA="$SHA"; COSIM_SIZE="$SIZE"
read SHA SIZE <<<"$(sha_of "$CTRL_DLL")"
CTRL_SHA="$SHA"; CTRL_SIZE="$SIZE"








need () { [ -n "$2" ] || { echo "SETUP-FAIL: $1 came out empty"; exit 2; }; }
read SHA SIZE <<<"$(sha_of cosim_vdot.exe)";   need "harness exe sha" "$SHA";   EXE_SHA="$SHA";  EXE_SIZE="$SIZE"
read SHA SIZE <<<"$(sha_of cosim_vdot.c)";     need "work-copy sha" "$SHA";     WORK_SRC="$SHA"
PKG_COSIM_C="$HERE/nemu/cosim/cosim_vdot.c"
read SHA SIZE <<<"$(sha_of "$PKG_COSIM_C")";   need "package sha" "$SHA";       PKG_SRC="$SHA"
[ "$WORK_SRC" = "$PKG_SRC" ] || { echo "SETUP-FAIL: $WORK/cosim_vdot.c != $PKG_COSIM_C (the exe this archive describes was built from a different source than the package ships)"; exit 2; }
BRIDGE="$HERE/nemu/cosim/rtl_vectors_to_cosim.py"
read SHA SIZE <<<"$(sha_of "$BRIDGE")";        need "bridge sha" "$SHA";        BRIDGE_SHA="$SHA"
read SHA SIZE <<<"$(sha_of cases_rtl.txt)";    need "cases sha" "$SHA";         CASES_SHA="$SHA"; CASES_BYTES="$SIZE"
CASES_LINES=$(grep -c -v '^#' cases_rtl.txt)
COMPOSITION=$($PY "$BRIDGE" --composition)
need "case composition" "$COMPOSITION"
need "cases line count" "$CASES_LINES"






{
  echo "# generated by nemu/cosim/capture_cosim.sh -- do not edit"
  echo "cases file: cases_rtl.txt source: tests/cases_{pos,neg,bound,rand}.txt"
  echo "[dll] cosim-arm path=$COSIM_DLL sha256=$COSIM_SHA size=$COSIM_SIZE"
  echo "[dll] control-arm path=$CTRL_DLL sha256=$CTRL_SHA size=$CTRL_SIZE"
  echo "[harness] exe path=$WORK/cosim_vdot.exe sha256=$EXE_SHA size=$EXE_SIZE source_sha256=$PKG_SRC work_copy_sha256=$WORK_SRC"
  echo "[bridge] script_sha256=$BRIDGE_SHA cases_path=$WORK/cases_rtl.txt cases_sha256=$CASES_SHA cases_bytes=$CASES_BYTES cases_lines=$CASES_LINES inputs=$COMPOSITION"
  echo ""
  ./cosim_vdot.exe "$COSIM_DLL" cases_rtl.txt > run_patched.log 2>&1
  echo "patched-arm rc=$?"
  ./cosim_vdot.exe "$CTRL_DLL" cases_rtl.txt > run_control.log 2>&1
  echo "control-arm rc=$?"
  ./cosim_vdot.exe "$COSIM_DLL" cases_rtl.txt --inject-bug > run_inject.log 2>&1
  echo "positive-control rc=$?"
  echo ""
  echo "=== patched arm (requirement 3.1.2 result) ==="
  grep -a "^library\|^vdot.vv\|^cases=" run_patched.log
  echo "=== unpatched control arm (must NOT reproduce it) ==="
  grep -a "^cases=\|^MISMATCH" run_control.log | head -3
  echo "=== positive control on the patched arm ==="
  grep -a "^cases=\|POSITIVE CONTROL" run_inject.log
} > "$OUT" 2>&1


{
  echo ""
  echo "[cosim] $(grep -a '^cases=' run_patched.log | tail -1)"
  echo "[control-arm] $(grep -a '^cases=' run_control.log | tail -1)"
  echo "[positive-control] $(grep -a 'POSITIVE CONTROL' run_inject.log | tail -1)"
  echo "[first-control-mismatch] $(grep -a '^MISMATCH' run_control.log | head -1)"
} >> "$OUT"

















DUMPER="$HERE/sim/rtl_vd_dump.py"
MUT=M6_drop_lane0
if [ ! -f "$DUMPER" ]; then
  echo "RTL_ARM NOT_RUN: $DUMPER missing -- the direct-collision claim is not supported"
  exit 0
fi
{
  echo ""
  echo "=== RTL counterparty arms ==="
  $PY "$DUMPER" --emit-rows ship "$WORK/rows_ship.txt" > rows_ship.log 2>&1
  echo "rows-ship rc=$? $(grep -a '^RTL_ROWS' rows_ship.log | tail -1)"
  $PY "$DUMPER" --emit-rows "$MUT" "$WORK/rows_mut.txt" > rows_mut.log 2>&1
  echo "rows-mutant rc=$? $(grep -a '^RTL_ROWS' rows_mut.log | tail -1)"
  [ -s "$WORK/rows_ship.txt" ] && [ -s "$WORK/rows_mut.txt" ] \
    || { echo "RTL_ARM BROKEN: a rows file came out empty"; exit 0; }

  $PY "$HERE/nemu/cosim/rtl_vectors_to_cosim.py" "$WORK/cases_rtlship.txt" \
       --expectations-from "$WORK/rows_ship.txt" > bridge_ship.log 2>&1
  echo "bridge-ship rc=$? $(grep -a '^BRIDGE_' bridge_ship.log | tail -1)"
  $PY "$HERE/nemu/cosim/rtl_vectors_to_cosim.py" "$WORK/cases_rtlnemu.txt" \
       --expectations-from "$WORK/rows_mut.txt" > bridge_mut.log 2>&1
  echo "bridge-mutant rc=$? $(grep -a '^BRIDGE_' bridge_mut.log | tail -1)"
  NEED_KEYS=$(grep -a '^BRIDGE_' bridge_mut.log | tail -1)
  [ -n "$NEED_KEYS" ] || { echo "RTL_ARM BROKEN: the mutant bridge printed no BRIDGE_ line"; exit 0; }



  R3_ROW=41
  R3_ORIG=$(grep -v '^#' cases_rtlship.txt | sed -n "${R3_ROW}p")
  need "R3 target row" "$R3_ORIG"
  $PY - "$WORK/cases_rtlship.txt" "$WORK/cases_rtlflip.txt" "$R3_ROW" > flip.log 2>&1 <<'PYEOF'
import io, sys
src, dst, line = sys.argv[1], sys.argv[2], int(sys.argv[3])
rows = io.open(src, encoding="utf-8", newline="").read().split("\n")
phys = 0
for i, ln in enumerate(rows):
    if ln.startswith("#") or not ln.strip():
        continue
    phys += 1
    if phys == line:
        f = ln.split()
        assert len(f) == 3, "row %d is not three fields: %r" % (line, ln)
        rows[i] = "%s %s %08x" % (f[0], f[1], int(f[2], 16) ^ 0x1)
        break
else:
    raise SystemExit("no such logical row %d" % line)
io.open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(rows))
note = "R3_FLIP logical_row=%d flipped_low_bit=1" % line
print(note)
PYEOF
  echo "flip rc=$?"

  ./cosim_vdot.exe "$COSIM_DLL" cases_rtlship.txt > run_r1.log 2>&1
  echo "r1 rc=$?"
  ./cosim_vdot.exe "$COSIM_DLL" cases_rtlnemu.txt > run_r2.log 2>&1
  echo "r2 rc=$?"
  ./cosim_vdot.exe "$COSIM_DLL" cases_rtlflip.txt > run_r3.log 2>&1
  echo "r3 rc=$?"
  echo "--- R1 (shipped RTL as expectation) ---"
  grep -a "^cases=" run_r1.log
  echo "--- R2 ($MUT's RTL values as expectation) ---"
  grep -a "^cases=\|^MISMATCH" run_r2.log | head -2
  echo "--- R3 (one expectation flipped) ---"
  grep -a "^cases=\|^MISMATCH" run_r3.log | head -2
} >> "$OUT" 2>&1

{
  echo ""
  echo "[rtl-arm-r1] $(grep -a '^cases=' run_r1.log | tail -1)"
  echo "[rtl-arm-r1-source] $(grep -a '^BRIDGE_' bridge_ship.log | tail -1)"
  echo "[rtl-arm-r2] $(grep -a '^cases=' run_r2.log | tail -1)"
  echo "[rtl-arm-r2-source] $(grep -a '^BRIDGE_' bridge_mut.log | tail -1)"
  echo "[rtl-arm-r2-first] $(grep -a '^MISMATCH' run_r2.log | head -1)"
  echo "[rtl-arm-r3] $(grep -a '^cases=' run_r3.log | tail -1)"
  echo "[rtl-arm-r3-row] $(grep -a '^R3_FLIP' flip.log | tail -1 | sed 's/^R3_FLIP //')"
  echo "[rtl-arm-r3-first] $(grep -a '^MISMATCH' run_r3.log | head -1)"
  echo "[rtl-rows] ship=$(grep -a '^RTL_ROWS' rows_ship.log | tail -1) mutant=$(grep -a '^RTL_ROWS' rows_mut.log | tail -1)"
} >> "$OUT"

echo "CAPTURE_RC=$?"
cat "$OUT"
