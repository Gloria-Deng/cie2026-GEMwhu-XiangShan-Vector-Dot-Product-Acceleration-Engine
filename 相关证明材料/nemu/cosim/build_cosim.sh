$PY - <<'PYEOF'
import io, re
txt = io.open("probe_out.txt", encoding="utf-8", errors="replace").read()
m = re.search(r"LAYOUT_BEGIN\n(.*?)LAYOUT_END", txt, re.S)
assert m, "probe printed no LAYOUT block -- probe_out.txt:\n" + txt[:600]
kv = dict(l.split() for l in m.group(1).strip().splitlines())
need = ["OFF_GPR", "OFF_PC", "OFF_MODE", "OFF_MSTATUS", "OFF_VR", "VR_STRIDE",
        "OFF_VSTART", "OFF_VTYPE", "OFF_VL", "OFF_END", "STATE_SIZE"]
missing = [k for k in need if k not in kv]
assert not missing, "layout probe missing: %s" % missing
for k in need:
    int(kv[k])                       # every value must be a plain integer
out = ["/* generated by build_cosim.sh from probe_offsets.c -- do not edit */",
       "#ifndef COSIM_LAYOUT_H", "#define COSIM_LAYOUT_H"]
for k in need:
    out.append("#define %-12s %s" % (k, kv[k]))
out.append("#endif")
io.open("cosim_layout.h", "w", encoding="utf-8", newline="\n").write(
    "\n".join(out) + "\n")
print("layout header: " + " ".join("%s=%s" % (k, kv[k]) for k in ("OFF_VR", "OFF_END", "STATE_SIZE")))
PYEOF




$PY - "$NCASE" <<'PYEOF'
import io, os, random, sys
sys.path.insert(0, r"D:\Desktop\RSIC-V香山\submission\sim")
import golden_vdot as G

n = int(sys.argv[1])
lines = ["# vs1(16B hex) vs2(16B hex) expected vd[0] as 32-bit LE hex"]
rnd = random.Random(20260924)
for i in range(n):
    lo = [rnd.randrange(256) for _ in range(8)]
    hi1 = [rnd.randrange(256) for _ in range(8)]      # ignored lanes
    hi2 = [rnd.randrange(256) for _ in range(8)]
    a = lo + hi1
    b = lo[:] + hi2                                    # same low lanes => easy maths
    # keep the two operands independent: re-roll b's low lanes
    b = [rnd.randrange(256) for _ in range(8)] + hi2
    exp = G.vdot_vd_bits(a, b, nlanes=8, out_w=32, vlen=128)
    lines.append("%s %s %08x" % (bytes(a).hex(), bytes(b).hex(), exp))
io.open("cases.txt", "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("cases.txt lines=%d" % (len(lines) - 1))
PYEOF

bash cc.sh cosim_vdot.c cosim_vdot.exe > cosim_cc.log 2>&1 || { echo "BUILD-FAILED"; tail -20 cosim_cc.log; exit 1; }
